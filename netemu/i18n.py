LANGUAGES = {"ru": "Русский", "en": "English"}
_lang = "ru"


def set_language(lang: str) -> None:
    global _lang
    _lang = lang if lang in LANGUAGES else "ru"


def language() -> str:
    return _lang


def tr(text: str, **fmt) -> str:
    s = EN.get(text, text) if _lang == "en" else text
    return s.format(**fmt) if fmt else s


